"""Build ReagentScout/Data.lua from QuestieDB's Forever data.

usage: python -I extract.py <itemDB.lua> <npcDB.lua> <areaIdToUiMapId.lua> <out Data.lua> <questiedb commit>
Keeps vendor-sold items of class 5 (Reagent) and 7 (Trade Goods), the vendors that
sell them, and the zone table entries those vendors need.
"""
import re
import sys

REAGENT_CLASSES = {5, 7}
ITEM_NAME, ITEM_CLASS, ITEM_VENDORS = 1, 12, 14
NPC_NAME, NPC_SPAWNS, NPC_FRIENDLY, NPC_SUB = 1, 7, 13, 14
MAX_SPAWNS = 6


class Parser:
    """Minimal parser for the Lua table literals QuestieDB generates."""

    def __init__(self, s):
        self.s, self.i = s, 0

    def ws(self):
        s, n = self.s, len(self.s)
        while self.i < n:
            if s[self.i] in " \t\r\n":
                self.i += 1
            elif s.startswith("--", self.i):  # line comment
                end = s.find("\n", self.i)
                self.i = n if end < 0 else end
            else:
                break

    def value(self):
        self.ws()
        c = self.s[self.i]
        if c == "{":
            return self.table()
        if c in "'\"":
            return self.string(c)
        m = re.compile(r"-?\d+(\.\d+)?(e-?\d+)?|nil|true|false").match(self.s, self.i)
        if not m:
            raise ValueError("unexpected %r at %d" % (self.s[self.i:self.i + 30], self.i))
        self.i = m.end()
        tok = m.group(0)
        if tok == "nil":
            return None
        if tok in ("true", "false"):
            return tok == "true"
        return float(tok) if ("." in tok or "e" in tok) else int(tok)

    def string(self, q):
        self.i += 1
        out = []
        while True:
            c = self.s[self.i]
            if c == "\\":
                out.append(self.s[self.i + 1])
                self.i += 2
            elif c == q:
                self.i += 1
                return "".join(out)
            else:
                out.append(c)
                self.i += 1

    def table(self):
        self.i += 1
        result, n = {}, 1
        while True:
            self.ws()
            if self.s[self.i] == "}":
                self.i += 1
                return result
            if self.s[self.i] == "[":
                self.i += 1
                key = self.value()
                self.ws()
                assert self.s[self.i] == "]"
                self.i += 1
                self.ws()
                assert self.s[self.i] == "="
                self.i += 1
                result[key] = self.value()
            else:
                result[n] = self.value()
                n += 1
            self.ws()
            if self.s[self.i] in ",;":
                self.i += 1


def rows(path, marker):
    text = open(path, encoding="utf-8").read()
    start = text.index(marker)
    body = text[text.index("return {", start) + len("return "):]
    body = body[: body.index("}]]") + 1]
    return Parser(body).value()


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def num(x):
    return ("%.2f" % x).rstrip("0").rstrip(".") if isinstance(x, float) else str(x)


def main():
    item_path, npc_path, zone_path, out_path, commit = sys.argv[1:6]
    items = rows(item_path, "QuestieDB.itemData")
    npcs = rows(npc_path, "QuestieDB.npcData")
    zones = rows(zone_path, "ZoneDB.private.areaIdToUiMapId =")
    overrides = rows(zone_path, "ZoneDB.private.areaIdToUiMapIdOverride")

    keep_items, vendor_ids = {}, set()
    for item_id, row in items.items():
        if row.get(ITEM_CLASS) in REAGENT_CLASSES and row.get(ITEM_VENDORS):
            vendors = [v for v in row[ITEM_VENDORS].values() if v in npcs]
            if vendors:
                keep_items[item_id] = (row.get(ITEM_NAME), sorted(vendors))
                vendor_ids.update(vendors)

    keep_npcs, areas = {}, set()
    for npc_id in sorted(vendor_ids):
        row = npcs[npc_id]
        points = []
        for area_id, pts in sorted((row.get(NPC_SPAWNS) or {}).items()):
            for p in pts.values():
                x, y = p.get(1), p.get(2)
                if x is not None and y is not None and x >= 0 and y >= 0 and len(points) < MAX_SPAWNS:
                    points.append((area_id, x, y))
                    areas.add(area_id)
        if points:
            keep_npcs[npc_id] = (row.get(NPC_NAME), row.get(NPC_SUB), row.get(NPC_FRIENDLY), points)

    merged = dict(zones)
    merged.update(overrides)
    zone_map = {a: merged[a] for a in sorted(areas) if merged.get(a)}

    out = []
    out.append("-- Generated by tools/extract.py from QuestieDB's Forever data. Do not edit by hand.")
    out.append("-- Source: https://github.com/Questie/QuestieDB (data/Forever, support/Forever) at %s" % commit)
    out.append("-- That data is licensed under the GNU GPL v3; so is this file. See LICENSE.md.")
    out.append("-- Vendor-sold Reagent (class 5) and Trade Goods (class 7) items only.")
    out.append("local _, ns = ...")
    out.append("ns.data = {}")
    out.append("-- [itemID] = { vendor NPC IDs }   (item name in the comment)")
    out.append("ns.data.items = {")
    for item_id in sorted(keep_items):
        name, vendors = keep_items[item_id]
        out.append("[%d]={%s}, -- %s" % (item_id, ",".join(map(str, vendors)), name))
    out.append("}")
    out.append("-- [npcID] = { name, subName, friendlyTo (\"A\", \"H\", \"AH\" or nil), {areaID, x, y, ...} }")
    out.append("ns.data.npcs = {")
    for npc_id in sorted(keep_npcs):
        name, sub, friendly, points = keep_npcs[npc_id]
        flat = ",".join("%d,%s,%s" % (a, num(x), num(y)) for a, x, y in points)
        out.append("[%d]={%s,%s,%s,{%s}}," % (
            npc_id, lua_str(name), lua_str(sub) if sub else "nil", lua_str(friendly) if friendly else "nil", flat))
    out.append("}")
    out.append("-- [areaID] = uiMapID (Forever zone table)")
    out.append("ns.data.zones = {")
    out.append(",".join("[%d]=%d" % (a, m) for a, m in zone_map.items()))
    out.append("}")
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("items %d, vendors %d, zones %d" % (len(keep_items), len(keep_npcs), len(zone_map)))


if __name__ == "__main__":
    main()
